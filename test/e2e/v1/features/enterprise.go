// entAPI calls an enterprise API of frps or frpc and returns its data.
func entAPI(port int, method, path string, body any) (json.RawMessage, error) {
	var r io.Reader
	if body != nil {
		b, err := json.Marshal(body)
		if err != nil {
			return nil, err
		}
		r = bytes.NewReader(b)
	}
	req, err := http.NewRequest(method, fmt.Sprintf("http://127.0.0.1:%d%s", port, path), r)
	if err != nil {
		return nil, err
	}
	req.SetBasicAuth("admin", "admin")
	req.Header.Set("Content-Type", "application/json")
	resp, err := (&http.Client{Timeout: 5 * time.Second}).Do(req)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	raw, err := io.ReadAll(resp.Body)
	if err != nil {
		return nil, err
	}
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s %s: %d %s", method, path, resp.StatusCode, raw)
	}
	var env struct {
		Code int             `json:"code"`
		Data json.RawMessage `json:"data"`
	}
	if err := json.Unmarshal(raw, &env); err != nil || env.Code == 0 {
		// frpc admin API responses have no envelope.
		return raw, nil
	}
	return env.Data, nil
}

func mustEntAPI(port int, method, path string, body any) json.RawMessage {
	data, err := entAPI(port, method, path, body)
	framework.ExpectNoError(err)
	return data
}

type entCode struct {
	Code          string `json:"code"`
	Status        string `json:"status"`
	BoundClientID string `json:"boundClientID"`
	Online        bool   `json:"online"`
}

func entCodes(port int, status string) []entCode {
	var codes []entCode
	framework.ExpectNoError(json.Unmarshal(mustEntAPI(port, "GET", "/api/enterprise/codes?status="+status, nil), &codes))
	return codes
}

// seedEntStore writes an enterprise store holding approved, unbound codes.
func seedEntStore(path string, codes ...string) {
	entries := map[string]any{}
	now := time.Now().UTC().Format(time.RFC3339)
	for _, c := range codes {
		entries[c] = map[string]any{"code": c, "status": "approved", "source": "server", "createdAt": now, "updatedAt": now}
	}
	b, err := json.Marshal(map[string]any{"codes": entries})
	framework.ExpectNoError(err)
	framework.ExpectNoError(os.WriteFile(path, b, 0o600))
}

var _ = ginkgo.Describe("[Feature: Enterprise]", func() {
	f := framework.NewDefaultFramework()

	type entEnv struct {
		webPort   int
		storePath string
		serverCfg string
	}
	newEnv := func(seed ...string) entEnv {
		e := entEnv{webPort: f.AllocPort(), storePath: filepath.Join(f.TempDirectory, fmt.Sprintf("ent-%d.json", time.Now().UnixNano()))}
		if len(seed) > 0 {
			seedEntStore(e.storePath, seed...)
		}
		e.serverCfg = consts.DefaultServerConfig + fmt.Sprintf(`
		webServer.addr = "127.0.0.1"
		webServer.port = %d
		webServer.user = "admin"
		webServer.password = "admin"
		enterprise.enabled = true
		enterprise.storePath = "%s"
		`, e.webPort, e.storePath)
		return e
	}
	clientCfg := func(clientID, code, proxyName string, remotePort int, extra string) string {
		cfg := consts.DefaultClientConfig + fmt.Sprintf(`
		clientID = "%s"
		user = "%s"
		`, clientID, clientID)
		if code != "" {
			cfg += fmt.Sprintf(`enterprise.authCode = "%s"
		`, code)
		}
		cfg += extra
		cfg += fmt.Sprintf(`
		[[proxies]]
		name = "%s"
		type = "tcp"
		localPort = {{ .%s }}
		remotePort = %d
		`, proxyName, framework.TCPEchoServerPort, remotePort)
		return cfg
	}

	ginkgo.It("refuses a client without an auth code", func() {
		e := newEnv()
		remotePort := f.AllocPort()
		_, clients := f.RunProcesses(e.serverCfg, []string{clientCfg("dev-a", "", "tcp", remotePort, "")})
		framework.ExpectNoError(clients[0].WaitForOutput("ent:required", 1, 10*time.Second))
		framework.NewRequestExpect(f).Port(remotePort).ExpectError(true).Ensure()
	})

	ginkgo.It("accepts a code generated by the server and binds it to one device", func() {
		code := "E2EA-AAAA-BBBB-CCCC"
		e := newEnv(code)
		remotePort := f.AllocPort()
		adminPort := f.AllocPort()
		_, clients := f.RunProcesses(e.serverCfg, []string{clientCfg("dev-a", code, "tcp", remotePort, fmt.Sprintf(`
		webServer.addr = "127.0.0.1"
		webServer.port = %d
		webServer.user = "admin"
		webServer.password = "admin"
		`, adminPort))})
		_ = clients
		framework.NewRequestExpect(f).Port(remotePort).Ensure()

		codes := entCodes(e.webPort, "approved")
		gomega.Expect(codes).To(gomega.HaveLen(1))
		gomega.Expect(codes[0].BoundClientID).To(gomega.Equal("dev-a"))
		gomega.Expect(codes[0].Online).To(gomega.BeTrue())

		// frpc received the snapshot with its own port and its public IP.
		gomega.Eventually(func() string {
			data, err := entAPI(adminPort, "GET", "/api/enterprise/state", nil)
			if err != nil {
				return err.Error()
			}
			return string(data)
		}, 10*time.Second, 200*time.Millisecond).Should(gomega.And(
			gomega.ContainSubstring(fmt.Sprintf(`"port":%d`, remotePort)),
			gomega.ContainSubstring(`"mine":true`),
			gomega.ContainSubstring(`"client_ip":"127.0.0.1"`),
		))

		// Another device with the same code is refused.
		otherPort := f.AllocPort()
		p, _, err := f.StartFrpc("-c", f.GenerateConfigFile(renderClient(f, clientCfg("dev-b", code, "tcp2", otherPort, ""))))
		framework.ExpectNoError(err)
		framework.ExpectNoError(p.WaitForOutput("ent:bound", 1, 10*time.Second))
	})

	ginkgo.It("waits for approval of a code generated by the client", func() {
		code := "E2EC-LIEN-TGEN-CODE"
		e := newEnv()
		remotePort := f.AllocPort()
		_, clients := f.RunProcesses(e.serverCfg, []string{clientCfg("dev-a", code, "tcp", remotePort, "")})
		framework.ExpectNoError(clients[0].WaitForOutput("ent:pending", 1, 10*time.Second))
		framework.NewRequestExpect(f).Port(remotePort).ExpectError(true).Ensure()

		pending := entCodes(e.webPort, "pending")
		gomega.Expect(pending).To(gomega.HaveLen(1))
		gomega.Expect(pending[0].Code).To(gomega.Equal(code))

		mustEntAPI(e.webPort, "POST", "/api/enterprise/codes/"+code+"/approve", nil)
		framework.ExpectNoError(framework.WaitForTCPReady(fmt.Sprintf("127.0.0.1:%d", remotePort), 30*time.Second))
		framework.NewRequestExpect(f).Port(remotePort).Ensure()
	})

	ginkgo.It("keeps a rejected client out", func() {
		code := "E2ER-EJEC-TEDC-ODE1"
		e := newEnv()
		remotePort := f.AllocPort()
		_, clients := f.RunProcesses(e.serverCfg, []string{clientCfg("dev-a", code, "tcp", remotePort, "")})
		framework.ExpectNoError(clients[0].WaitForOutput("ent:pending", 1, 10*time.Second))
		mustEntAPI(e.webPort, "POST", "/api/enterprise/codes/"+code+"/reject", nil)
		framework.ExpectNoError(clients[0].WaitForOutput("ent:rejected", 1, 30*time.Second))
		framework.NewRequestExpect(f).Port(remotePort).ExpectError(true).Ensure()
	})

	ginkgo.It("disconnects a revoked client", func() {
		code := "E2ER-EVOK-EDCO-DE22"
		e := newEnv(code)
		remotePort := f.AllocPort()
		_, clients := f.RunProcesses(e.serverCfg, []string{clientCfg("dev-a", code, "tcp", remotePort, "")})
		framework.NewRequestExpect(f).Port(remotePort).Ensure()

		mustEntAPI(e.webPort, "POST", "/api/enterprise/codes/"+code+"/revoke", nil)
		framework.ExpectNoError(framework.WaitForTCPUnreachable(fmt.Sprintf("127.0.0.1:%d", remotePort), 100*time.Millisecond, 10*time.Second))
		framework.ExpectNoError(clients[0].WaitForOutput("ent:rejected", 1, 30*time.Second))
	})

	ginkgo.It("does not let a client take a port held by another client", func() {
		code1, code2 := "E2EP-ORTA-AAAA-AAAA", "E2EP-ORTB-BBBB-BBBB"
		e := newEnv(code1, code2)
		remotePort := f.AllocPort()
		_, clients := f.RunProcesses(e.serverCfg, []string{
			clientCfg("dev-a", code1, "first", remotePort, ""),
		})
		framework.NewRequestExpect(f).Port(remotePort).Ensure()
		_ = clients

		p, _, err := f.StartFrpc("-c", f.GenerateConfigFile(renderClient(f, clientCfg("dev-b", code2, "second", remotePort, ""))))
		framework.ExpectNoError(err)
		framework.ExpectNoError(p.WaitForOutput("already used by another client", 1, 10*time.Second))
		framework.NewRequestExpect(f).Port(remotePort).Ensure()

		var ports []struct {
			Port     int    `json:"port"`
			AuthCode string `json:"authCode"`
		}
		framework.ExpectNoError(json.Unmarshal(mustEntAPI(e.webPort, "GET", "/api/enterprise/ports", nil), &ports))
		gomega.Expect(ports).To(gomega.HaveLen(1))
		gomega.Expect(ports[0].AuthCode).To(gomega.Equal(code1))
	})

	ginkgo.It("delivers notices to clients", func() {
		code := "E2EN-OTIC-EEEE-EEEE"
		e := newEnv(code)
		remotePort := f.AllocPort()
		adminPort := f.AllocPort()
		f.RunProcesses(e.serverCfg, []string{clientCfg("dev-a", code, "tcp", remotePort, fmt.Sprintf(`
		webServer.addr = "127.0.0.1"
		webServer.port = %d
		webServer.user = "admin"
		webServer.password = "admin"
		`, adminPort))})
		framework.NewRequestExpect(f).Port(remotePort).Ensure()

		mustEntAPI(e.webPort, "POST", "/api/enterprise/notices", map[string]string{
			"level": "warning", "title": "maintenance tonight", "content": "frps restarts at 22:00",
		})
		gomega.Eventually(func() string {
			data, _ := entAPI(adminPort, "GET", "/api/enterprise/state", nil)
			return string(data)
		}, 10*time.Second, 200*time.Millisecond).Should(gomega.ContainSubstring("maintenance tonight"))

		var notices []struct {
			Title string `json:"title"`
		}
		framework.ExpectNoError(json.Unmarshal(mustEntAPI(e.webPort, "GET", "/api/enterprise/notices", nil), &notices))
		gomega.Expect(notices).To(gomega.HaveLen(1))
		gomega.Expect(strings.Contains(notices[0].Title, "maintenance")).To(gomega.BeTrue())
	})
})

// renderClient fills the port placeholders of a client config template with
// the framework's allocated ports.
func renderClient(f *framework.Framework, tmpl string) string {
	outs, _, err := f.RenderTemplates([]string{tmpl})
	framework.ExpectNoError(err)
	return outs[0]
}
